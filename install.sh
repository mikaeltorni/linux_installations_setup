# Snap applications, split so each is independently selectable via components.
SNAP_GITKRAKEN=("gitkraken --classic")
SNAP_SPOTIFY=("spotify")
SNAP_DISCORD=("discord")
SNAP_APPS=("${SNAP_GITKRAKEN[@]}" "${SNAP_SPOTIFY[@]}" "${SNAP_DISCORD[@]}")

# Component selection runtime and this repository's component manifest. The
# manifest maps each component id to an install_* step from the lib files above.
# The framework was already resolved above (for isc_load_helpers); activate the
# component runtime from the same checkout.
isc_activate_components
source "$SCRIPT_DIR/installer/components.sh"

INSTALLER_NO_REBOOT="${INSTALLER_NO_REBOOT:-0}"

# main_inner — install the selected base-system components. Selection (root
# preflight, NVIDIA detection, etc.) is resolved by component_main.
main_inner() {
  msg "=== Linux Installation Setup ==="
  
  # Feature-specific installation support (--features=feature1,feature2,...)
  SELECTED_FEATURES="${FEATURES:-}"
  
  if [ -n "$SELECTED_FEATURES" ]; then
    IFS="," read -ra FEATURE_ARRAY <<< "$SELECTED_FEATURES"
    msg "Feature filter active: ${FEATURE_ARRAY[*]}"
    
    local select_arg=""
    for arg in "$@"; do
      if [[ "${arg}" == --select=* ]]; then
        local selected_components="${arg#--select=}"
        local filtered="" first=true
        
        for comp_id in ${selected_components}; do
          for feature in "${FEATURE_ARRAY[@]}"; do  
            if [ "$comp_id" = "$feature" ]; then
              if $first; then filtered="$comp_id"; first=false; else filtered="$filtered,$comp_id"; fi  
              break
            fi  
          done  
        done
        
        select_arg="--select=$filtered"
        break
      fi
    done
    
    # If no specific --select, use feature list directly as component IDs
    if [ -z "$select_arg" ]; then
      local features_as_components="" first=true
      for feature in "${FEATURE_ARRAY[@]}"; do
        if $first; then features_as_components="$feature"; first=false; else features_as_components="$features_as_components,$feature"; fi
      done
      select_arg="--select=$features_as_components"
    fi
    
    component_main "$select_arg"  
  else
    msg "Installing all configured components"
    component_main "$@"
  fi
  
  local rc=$?
  msg "=== Linux Installation Setup Complete ==="
  return $rc
}

run_and_log_with_reboot() {
  local ts log_dir log_file
  ts=$(date +"%Y%m%d-%H%M%S")
  log_dir="$SCRIPT_DIR/.log"
  mkdir -p "$log_dir"
  log_file="$log_dir/linux_installations_setup-$ts.log"
  
  main_inner "$@" 2>&1 | tee "$log_file"
  msg "All done. Log file written to: $log_file"
  
  if [[ "${INSTALLER_NO_REBOOT:-0}" == "1" ]]; then
    msg "Skipping reboot due to INSTALLER_NO_REBOOT=1"
  else
    safe_system_action reboot
  fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    # Listing/help must print only their own output (the master installer parses
    # --list-components) and must not require root or trigger a reboot.
    case "${1:-}" in
      --list-favorite-components) lis_list_favorite_components; exit $? ;;
      --list-startup-components) lis_list_startup_components; exit $? ;;
      --list-components|--export-selection|--detect|--help|-h|--uninstall|--uninstall=*) component_main "$@"; exit $? ;;
    esac
    run_and_log_with_reboot "$@"
fi
