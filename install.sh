#!/usr/bin/env bash
# install.sh — Linux Installation Setup (Phase 1 of 7)
#
# This installer handles base system setup:
#   - Installs base system packages and utilities
#   - Detects hardware (NVIDIA GPU) and installs drivers
#   - Installs applications (Baobab, Chrome, Etcher, snaps, GH CLI, Albert)
#
# Note: Repository cloning and sub-repo orchestration is handled by the
# master installer at installation_scripts/install.sh. This script focuses
# only on base packages, hardware detection, and application installation.
#
# Usage: sudo bash install.sh

set -euo pipefail

TARGET_USER="${SUDO_USER:-$USER}"
TARGET_UID="$(id -u "$TARGET_USER")"
TARGET_HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNTIME_DIR="/run/user/${TARGET_UID}"
DISPLAY_VAL="${DISPLAY:-:0}"
USER_BUS="unix:path=${RUNTIME_DIR}/bus"

ETCHER_VERSION="${ETCHER_VERSION:-latest}"
BLUETOOTH_KERNEL_VERSION="${BLUETOOTH_KERNEL_VERSION:-6.17.0-40-generic}"

source "$SCRIPT_DIR/lib/logging.sh"

# Load the shared installer framework + shared install-time helpers (single
# source of truth in linux_installation_scripts_functions) before any library
# uses run_as_target/msg/need_cmd/ensure_root. No vendored copy: resolve a
# sibling checkout or download on demand.
# Generated by the shared framework owner; works without sibling downloads.
source "$SCRIPT_DIR/.installer-support/bootstrap.sh"
isc_load_helpers

source "$SCRIPT_DIR/lib/hardware.sh"
source "$SCRIPT_DIR/lib/apt_helpers.sh"
source "$SCRIPT_DIR/lib/bluetooth.sh"
source "$SCRIPT_DIR/lib/inotify_limits.sh"
source "$SCRIPT_DIR/lib/system_services.sh"
source "$SCRIPT_DIR/lib/nodejs_installer.sh"

APT_UPDATED=0

# Base packages are split into feature groups so every feature is an
# independently selectable component (see installer/components.sh). Each group
# is default-on, so a clean install reproduces the full package set unless the
# user deselects a group. The aggregate APT_BASE_PACKAGES is retained as the
# union of all groups for backward compatibility and documentation/tests.

# Core CLI utilities used throughout the setup family. Each tool has its own
# array/component so it can be selected independently; APT_CORE_UTILS remains
# their compatibility union for install_base_packages and external callers.
APT_GIT=(git)
APT_CURL=(curl)
APT_GPG=(gpg)
APT_JQ=(jq)
APT_7ZIP=(p7zip-full)
APT_CORE_UTILS=(
  "${APT_GIT[@]}" "${APT_CURL[@]}" "${APT_GPG[@]}" "${APT_JQ[@]}"
  "${APT_7ZIP[@]}"
)

# GNOME Shell extension and tweak tooling consumed by the configuration repos.
APT_GNOME_TOOLING=(
  gnome-shell-extension-manager chrome-gnome-shell gnome-tweaks
  gnome-shell-extension-prefs dconf-cli dconf-service
)

# Build toolchain and development headers for compiling extensions/helpers.
APT_BUILD_TOOLS=(make gettext build-essential pkg-config libx11-dev libxi-dev libev-dev)

# Kitty terminal emulator.
APT_TERMINAL=(kitty)

# GNOME Disk Usage Analyzer.
APT_BAOBAB=(baobab)
APT_GPARTED=(gparted)

# Python runtime and configuration libraries (evdev for hotkeys, Pillow for
# cursor assets, PyGObject plus Secret Service libraries for the keyring
# migration). The keyring libraries are intentionally part of this default group
# instead of a separate menu row: Ubuntu usually preinstalls them, but a clean
# minimal system still needs them for linux_configuration_setup.
APT_PYTHON=(
  python3 python3-evdev python3-pil python3-gi
  gnome-keyring gir1.2-secret-1 dbus-daemon
)

# X11 and desktop utilities (screenshotting, the documented Alt+F2 shell reload,
# desktop entry handling, key binding daemon).
APT_DESKTOP_UTILS=(
  xbindkeys gnome-screenshot x11-xserver-utils x11-apps xdotool desktop-file-utils
