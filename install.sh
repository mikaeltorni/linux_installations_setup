# Audio stack and speech synthesis (TTS announcements, sound theme).
APT_AUDIO_SPEECH=(
  pulseaudio-utils pipewire-audio speech-dispatcher espeak-ng sound-theme-freedesktop
)

# Optional hardware support for machines that need the distro-provided
# firmware and Bluetooth userspace stack. The kernel-side btusb/btmtk modules
# come from the running Ubuntu kernel and are not separate APT packages.
APT_ESSENTIAL_DRIVERS=(linux-firmware bluez)

# Multimedia applications. Keep each app independently selectable while
# retaining APT_MULTIMEDIA as the compatibility union.
APT_VLC=(vlc)
APT_OBS=(obs-studio)
APT_EASYEFFECTS=(easyeffects)
APT_MULTIMEDIA=("${APT_VLC[@]}" "${APT_OBS[@]}" "${APT_EASYEFFECTS[@]}")

# Remmina remote desktop client and RDP/secret plugins.
APT_REMOTE_DESKTOP=(remmina remmina-plugin-rdp remmina-plugin-secret)

# Terminal multiplexer.
APT_TMUX=(tmux)

# KVM/libvirt virtualization stack.
APT_VIRTUALIZATION=(virtinst virt-manager libvirt-daemon-system libvirt-clients bridge-utils)

# Union of every group; kept for backward compatibility and reference.
APT_BASE_PACKAGES=(
  "${APT_CORE_UTILS[@]}" "${APT_GNOME_TOOLING[@]}" "${APT_BUILD_TOOLS[@]}"
  "${APT_TERMINAL[@]}" "${APT_PYTHON[@]}" "${APT_DESKTOP_UTILS[@]}"
  "${APT_AUDIO_SPEECH[@]}" "${APT_MULTIMEDIA[@]}" "${APT_BAOBAB[@]}" "${APT_GPARTED[@]}" "${APT_REMOTE_DESKTOP[@]}"
  "${APT_TMUX[@]}" "${APT_VIRTUALIZATION[@]}"
